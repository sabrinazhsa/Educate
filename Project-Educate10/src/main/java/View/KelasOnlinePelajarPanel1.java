    public void setAksiIkutKelas(Consumer<KelasOnline> aksi) {
        this.aksiIkutKelas = aksi;
    }

    public void refreshData() {
        daftarKelas.removeAll();
        List<KelasOnline> data = kelasDao.getAllKelas();
        int jumlah = 0;

        for (KelasOnline kelas : data) {
            if (!sesuaiFilter(kelas)) continue;
            KartuKelasOnline kartu = new KartuKelasOnline();
            kartu.setData(kelas, this::pilihKelas);
            kartu.setAlignmentX(Component.LEFT_ALIGNMENT);
            kartu.setMaximumSize(new Dimension(Integer.MAX_VALUE, 190));
            daftarKelas.add(kartu);
            daftarKelas.add(Box.createVerticalStrut(12));
            jumlah++;
        }

        if (jumlah == 0) {
            javax.swing.JLabel kosong = new javax.swing.JLabel(
                "Belum ada kelas online untuk kategori " + filterAktif + "."
            );
            kosong.setAlignmentX(Component.CENTER_ALIGNMENT);
            daftarKelas.add(Box.createVerticalStrut(24));
            daftarKelas.add(kosong);
        }
        daftarKelas.revalidate();
        daftarKelas.repaint();
    }

    private void setFilter(String filter) {
        filterAktif = filter;
        refreshData();
    }

    private boolean sesuaiFilter(KelasOnline kelas) {
        if ("Semua".equalsIgnoreCase(filterAktif)) return true;
        String gabungan = (kelas.getNamaKelas() == null ? "" : kelas.getNamaKelas()) + " "
            + (kelas.getDeskripsiKelas() == null ? "" : kelas.getDeskripsiKelas()) + " "
            + (kelas.getPengajar() == null || kelas.getPengajar().getKeahlian() == null
                ? "" : kelas.getPengajar().getKeahlian());
        return gabungan.toLowerCase(Locale.ROOT)
            .contains(filterAktif.toLowerCase(Locale.ROOT));
    }

    private void pilihKelas(KelasOnline kelas) {
        if (aksiIkutKelas != null) {
            aksiIkutKelas.accept(kelas);
            return;
        }

        int pilihan = JOptionPane.showConfirmDialog(
            this,
            "Kelas: " + kelas.getNamaKelas() + "\n"
                + "Pengajar: " + (kelas.getPengajar() == null ? "-" : kelas.getPengajar().getNama())
                + "\nHarga: Rp " + kelas.getHarga()
                + "\n\nLanjut melihat informasi kelas?",
            "Detail Kelas Online",
            JOptionPane.YES_NO_OPTION
        );

    }

