    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
    int baris = tblKelas.getSelectedRow();
    if (baris < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih kelas yang ingin diubah dulu");
        return;
    }
    
    javax.swing.table.TableModel model = tblKelas.getModel();
    int b = tblKelas.convertRowIndexToModel(baris);

    String nama     = String.valueOf(model.getValueAt(b, 1));
    String jadwal     = String.valueOf(model.getValueAt(b, 2));
    String waktuMulai     = String.valueOf(model.getValueAt(b, 3));
    String waktuSelesai = String.valueOf(model.getValueAt(b, 4));
    String linkAkses = String.valueOf(model.getValueAt(b, 5));
    String harga = String.valueOf(model.getValueAt(b, 6));
    String status = String.valueOf(model.getValueAt(b, 7));


    java.awt.Frame frame = (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this);
    FormKelasDialog_1 dialog = new FormKelasDialog_1(frame, true);
    dialog.isiForm(nama, jadwal, waktuMulai, waktuSelesai, linkAkses, harga, status);
    dialog.setLocationRelativeTo(this);
    dialog.setVisible(true);
    
    if (dialog.isDisimpan()) {
        try { FormKelasDialog_1 d=dialog; int id=idKelasPadaBaris(b);
            dao.CrudDemoDao.jalankan("UPDATE kelas_online SET nama_kelas=?,tanggal_kelas=?,waktu_mulai=?,waktu_selesai=?,link_kelas=?,harga=?,status_kelas=? WHERE id_kelas=?",d.getNama(),dao.CrudDemoDao.tanggal(d.getJadwal()),d.getMulai(),d.getSelesai(),d.getAkses(),d.getharga(),d.getStatus(),id);
            muatDataKelas();
            javax.swing.JOptionPane.showMessageDialog(this,"Data berhasil diubah!");
        } catch(Exception ex){dao.CrudDemoDao.pesan(this,ex);} 
    }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {                                         
        int row=tblKelas.getSelectedRow();
        if(row<0){javax.swing.JOptionPane.showMessageDialog(this,"Pilih data terlebih dahulu!");return;}
        if(!dao.CrudDemoDao.konfirmasi(this))return;
        try {int id=idKelasPadaBaris(tblKelas.convertRowIndexToModel(row));
             dao.PenghapusanBerantaiDao.hapus("kelas",id); muatDataKelas();
             javax.swing.JOptionPane.showMessageDialog(this,"Data berhasil dihapus!");
        }catch(Exception ex){dao.CrudDemoDao.pesan(this,ex);}
    }



