    private int idKelasPadaBaris(int baris) throws java.sql.SQLException {
        try (java.sql.Connection c=config.EducateDB.getConnection();
             java.sql.PreparedStatement ps=c.prepareStatement("SELECT id_kelas FROM kelas_online ORDER BY id_kelas LIMIT 1 OFFSET ?")) {
            ps.setInt(1,baris);
            try(java.sql.ResultSet rs=ps.executeQuery()) {
                if(rs.next()) return rs.getInt(1);
            }
        }
        throw new java.sql.SQLException("Kelas tidak ditemukan. Muat ulang tabel.");
    }
