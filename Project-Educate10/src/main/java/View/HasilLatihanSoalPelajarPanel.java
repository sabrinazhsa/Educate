    public void setHasil(Object[] r) {
        int skor = ((Number) r[2]).intValue();
        int idHasil = ((Number) r[4]).intValue();
        String namaPaket = String.valueOf(r[1]);

        namaPaketAktif = namaPaket;
        topikAktif = "Semua";
        String sqlTopik = "SELECT m.topik FROM materi m WHERE ? LIKE CONCAT(m.nama_materi, ' - %') LIMIT 1";
        try (java.sql.Connection c = config.EducateDB.getConnection();
             java.sql.PreparedStatement ps = c.prepareStatement(sqlTopik)) {
            ps.setString(1, namaPaket);
            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (rs.next()) topikAktif = rs.getString(1);
            }
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
        }

        lblangka.setText(String.valueOf(skor));
        lblTopikmateri.setText(topikAktif);
        lblisirekom.setText(skor < 70
            ? "Karena nilai masih di bawah 70. Pelajari topik terlebih dahulu."
            : "Nilai kamu sudah baik. Lanjutkan ke tingkat berikutnya!");

        javax.swing.table.DefaultTableModel tm =
                (javax.swing.table.DefaultTableModel) tblHasil.getModel();
        tm.setRowCount(0);
        for (Object[] baris : new dao.HasilBelajarDao().getDetailSoal(idHasil)) {
            tm.addRow(baris);
        }
}

