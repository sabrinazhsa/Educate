    private void muatDataMateri() {

        DefaultTableModel model =
            (DefaultTableModel) tblMateri.getModel();

        model.setRowCount(0);

        List<Materi> daftar = controller.tampilkanMateri();

        for (Materi m : daftar) {
            model.addRow(new Object[]{
                m.getIdMateri(),
                m.getTipeMateri(),
                m.getNamaMateri(),
                m.getTopik(),
                m.getDeskripsiMateri(),
                "-"
            });
        }

        lblTotal.setText("Total Materi : " + daftar.size());
    }


