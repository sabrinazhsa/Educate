    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
    model.Pengguna login = controller.SessionManagerController.getPenggunaAktif();
    if (!(login instanceof model.Pelajar)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Data pelajar tidak ditemukan, silakan login ulang");
        return;
    }
    model.Pelajar p = (model.Pelajar) login;

    java.awt.Window w = javax.swing.SwingUtilities.getWindowAncestor(this);
    java.awt.Frame parent = (w instanceof java.awt.Frame) ? (java.awt.Frame) w : null;

    UbahProfilPelajarDialog dlg = new UbahProfilPelajarDialog(parent, true);
    dlg.isiForm(
        "",                          // password dikosongkan
        lblUsername.getText(),
        lblEmail.getText(),
        lblJK.getText(),
        lblLahir.getText(),
        lblTanggaldaftar.getText(),
        lblNama.getText(),
        lblKelas.getText()
    );
    dlg.setLocationRelativeTo(this);
    dlg.setVisible(true);

    if (!dlg.isDisimpan()) {
        return;
    }

    String passwordBaru = dlg.getPassword();
    try {
        p.setNama(dlg.getNama());
        p.setEmail(dlg.getEmail());
        p.setKelas(Integer.parseInt(dlg.getStatus()));
        if (!passwordBaru.isEmpty()) {
            p.setPassword(passwordBaru);      // validasi minimal 6 karakter
        }
    } catch (IllegalArgumentException e) {
        javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        return;
    }

    if (new dao.PenggunaDao().updateProfil(p, passwordBaru)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Profil berhasil diperbarui");
        muatProfil();   // tampilkan data terbaru
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan profil");
    }
    }//GEN-LAST:event_btnUbahActionPerformed

