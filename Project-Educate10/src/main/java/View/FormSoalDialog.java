    public FormSoalDialog(java.awt.Frame parent, boolean modal) {
    super(parent, modal);
    initComponents();
    cmbMateri.removeAllItems();
    java.util.LinkedHashSet<String> topikUnik = new java.util.LinkedHashSet<>();
    for (Materi m : new MateriDao().getAll()) {
        topikUnik.add(m.getTopik());
    }
    for (String t : topikUnik) {
        cmbMateri.addItem(t);
    }
    cmbMateri.addActionListener(e -> muatPaket());
    muatPaket();
}

private void muatPaket() {
    cmbPaket.removeAllItems();
    Object topik = cmbMateri.getSelectedItem();
    if (topik == null) return;

    // semua paket milik materi yang bertopik tersebut
    String sql = "SELECT p.nama_paket_soal FROM paket_soal p "
               + "JOIN materi m ON p.nama_paket_soal LIKE CONCAT(m.nama_materi, ' - %') "
               + "WHERE m.topik = ? ORDER BY p.id_paket_soal";
    try (Connection conn = EducateDB.getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {
        stmt.setString(1, String.valueOf(topik));
        try (ResultSet rs = stmt.executeQuery()) {
            while (rs.next()) {
                cmbPaket.addItem(rs.getString(1));
            }
        }
    } catch (java.sql.SQLException ex) {
        ex.printStackTrace();
    }
}

