    public void isiForm(String judul, String topik, String deskripsi, String jenis, String konten) {
    lblJudul.setText("Ubah Materi");
    txtJudul.setText(judul);
    cmbTopik.setSelectedItem(topik);
    txtDeskripsi.setText(deskripsi);
    txtPilih.setText(konten);
    if ("Video".equals(jenis)) rdoVideo.setSelected(true); else rdoTeks.setSelected(true);
}
    
