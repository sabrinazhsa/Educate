    private void muatTopik() {
    cmbTopik.removeAllItems();
    String sql = "SELECT DISTINCT topik FROM materi ORDER BY topik";
    try (Connection conn = EducateDB.getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql);
         ResultSet rs = stmt.executeQuery()) {
        while (rs.next()) {
            cmbTopik.addItem(rs.getString(1));
        }
    } catch (java.sql.SQLException ex) {
        ex.printStackTrace();
    }
}

