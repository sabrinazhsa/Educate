    public void bukaDashboard(model.Pengguna user) {
    String role = user.getRole();

    if (role.equalsIgnoreCase("Pengajar")) {
        dashboardPengajar.tampilkanHalaman("beranda");
        tampilkan("card2");
    } else if (role.equalsIgnoreCase("Pelajar")) {
        dashboardPelajar.tampilkanHalaman("beranda");
        tampilkan("card5");
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Role pengguna tidak dikenali: " + role
        );
    }
}
    
    public void tampilkan(String nama) {
    java.awt.CardLayout cl =
            (java.awt.CardLayout) getContentPane().getLayout();

    cl.show(getContentPane(), nama);
}
    
    public void ubahUkuran(int lebar, int tinggi) {
    getContentPane().setPreferredSize(new java.awt.Dimension(lebar, tinggi));
    pack();
    setLocationRelativeTo(null);
    
}


