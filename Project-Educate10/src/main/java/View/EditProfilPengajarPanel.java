    public void muatProfil() {
        model.Pengguna aktif = controller.SessionManagerController.getPenggunaAktif();
        if (aktif == null) return;
        String sql = "SELECT u.nama, u.email, u.username, u.jenis_kelamin, "
                + "u.tanggal_lahir, p.keahlian, p.status_pengajar "
                + "FROM pengguna u LEFT JOIN pengajar p ON p.id_pengguna = u.id_pengguna "
                + "WHERE u.id_pengguna = ? AND u.role = 'Pengajar'";
        try (java.sql.Connection c = config.EducateDB.getConnection()) {
            if (c == null) throw new java.sql.SQLException("Database tidak tersambung");
            try (java.sql.PreparedStatement ps = c.prepareStatement(sql)) {
                ps.setInt(1, aktif.getIdPengguna());
                try (java.sql.ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) throw new java.sql.SQLException("Akun pengajar tidak ditemukan");
                    lblNama.setText(teks(rs.getString("nama")));
                    lblEmail.setText(teks(rs.getString("email")));
                    lblUsername.setText(teks(rs.getString("username")));
                    lblJK.setText(teks(rs.getString("jenis_kelamin")));
                    java.sql.Date tanggal = rs.getDate("tanggal_lahir");
                    lblLahir.setText(tanggal == null ? "-" : tanggal.toString());
                    lblKeahlian.setText(teks(rs.getString("keahlian")));
                    lblStatus.setText(teks(rs.getString("status_pengajar")));
                    lblHalo.setText("HALO, " + rs.getString("nama").toUpperCase() + "!");
                }
            }
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Gagal memuat profil: " + ex.getMessage());
        }
    }

    private String teks(String s) {
        return s == null || s.isBlank() ? "-" : s;
    }

