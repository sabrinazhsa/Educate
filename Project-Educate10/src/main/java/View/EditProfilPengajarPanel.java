    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
    java.awt.Frame frame = (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this);
    UbahProfilPengajarDialog dialog = new UbahProfilPengajarDialog(frame, true);
    dialog.setLocationRelativeTo(this);
    dialog.isiForm(
    "",                          
    lblUsername.getText(),
    lblEmail.getText(),
    lblJK.getText(),
    lblLahir.getText(),
    lblKeahlian.getText(),      
    lblNama.getText(),
    lblStatus.getText()
);
    dialog.setVisible(true);
    if (dialog.isDisimpan()) {
    String passwordBaru = dialog.getPassword();
    String namaBaru = dialog.getNama();
    String emailBaru = dialog.getEmail();
    String statusBaru = dialog.getStatus();

    if (namaBaru.trim().isEmpty() || emailBaru.trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Nama dan email tidak boleh kosong");
        return;
    }
    if (!passwordBaru.isEmpty() && passwordBaru.length() < 6) {
        javax.swing.JOptionPane.showMessageDialog(this, "Password minimal 6 karakter");
        return;
    }

    model.Pengguna aktif = controller.SessionManagerController.getPenggunaAktif();
    boolean berhasil = new dao.PenggunaDao().updateProfilPengajar(
            aktif.getIdPengguna(), namaBaru.trim(), emailBaru.trim(), passwordBaru, statusBaru);

    if (berhasil) {
        try {
            aktif.setNama(namaBaru);     // samakan data sesi dengan database
            aktif.setEmail(emailBaru);
        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        }
        muatProfil();
        javax.swing.JOptionPane.showMessageDialog(this, "Profil berhasil diperbarui");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan profil");
    }
}
    }//GEN-LAST:event_btnUbahActionPerformed

