    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        int row = tblPelajar.getSelectedRow();
        if (row < 0) { javax.swing.JOptionPane.showMessageDialog(this, "Pilih pelajar dahulu"); return; }
        row = tblPelajar.convertRowIndexToModel(row);
        javax.swing.table.TableModel tm = tblPelajar.getModel();
        int id = Integer.parseInt(tm.getValueAt(row, 0).toString());
        java.awt.Frame parent = (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this);
        FormPelajarDialog form = new FormPelajarDialog(parent, true);
        form.isiForm(str(tm,row,0),str(tm,row,3),str(tm,row,2),str(tm,row,4),
                str(tm,row,5),str(tm,row,7),str(tm,row,1),str(tm,row,6));
        form.setLocationRelativeTo(this);
        form.setVisible(true);
        if (!form.isDisimpan()) return;
        String sql = "UPDATE pengguna SET nama=? WHERE id_pengguna=? AND role='Pelajar'";
        try (java.sql.Connection c = config.EducateDB.getConnection();
             java.sql.PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, form.getNama()); ps.setInt(2, id);
            if (ps.executeUpdate() > 0) {
                try (java.sql.PreparedStatement ps2 = c.prepareStatement("UPDATE pelajar SET kelas=? WHERE id_pengguna=?")) {
                    ps2.setInt(1, Integer.parseInt(form.getKelas())); ps2.setInt(2, id);
                    ps2.executeUpdate();
                }
                muatDataPelajar();
                javax.swing.JOptionPane.showMessageDialog(this, "Data pelajar berhasil diubah");
            }
        } catch (Exception ex) { javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengubah: " + ex.getMessage()); }
    }//GEN-LAST:event_btnUbahActionPerformed

    private static String str(javax.swing.table.TableModel tm, int r, int c) {
        Object v = tm.getValueAt(r,c); return v == null ? "" : v.toString();
    }

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int row = tblPelajar.getSelectedRow();
        if (row < 0) { javax.swing.JOptionPane.showMessageDialog(this, "Pilih pelajar dahulu"); return; }
        int id = Integer.parseInt(tblPelajar.getModel().getValueAt(tblPelajar.convertRowIndexToModel(row),0).toString());
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "Hapus pelajar beserta data terkait? Tindakan tidak dapat dibatalkan.",
            "Konfirmasi hapus", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirm != javax.swing.JOptionPane.YES_OPTION) return;
        try {
            dao.PenghapusanBerantaiDao.hapus("pelajar", id);
            muatDataPelajar();
            javax.swing.JOptionPane.showMessageDialog(this,"Pelajar dan seluruh data terkait berhasil dihapus");
        } catch (Exception ex) { dao.CrudDemoDao.pesan(this, ex); }
    }//GEN-LAST:event_btnHapusActionPerformed

