    private void muatDataPelajar() {
    DefaultTableModel model =
            (DefaultTableModel) tblPelajar.getModel();

    model.setRowCount(0);

    List<Object[]> daftar =
            controller.tampilkanPelajar();

    for (Object[] data : daftar) {
        model.addRow(data);
    }

    lblTotal.setText(
            "Total Pelajar Terdaftar : " + daftar.size()
    );
}
