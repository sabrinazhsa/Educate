    private void siapkanTabel() {
        tblRiwayat.setModel(new DefaultTableModel(
                new Object[][]{},
                new String[]{"Tanggal", "Paket Soal", "Skor", "Jawaban Benar"}));
        tblRiwayat.getTableHeader().setReorderingAllowed(false);
        tblRiwayat.getTableHeader().setResizingAllowed(false);
        tblRiwayat.setDefaultEditor(Object.class, null);
        tblRiwayat.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    }
    
     public void refreshData() {
        model.Pengguna user = controller.SessionManagerController.getPenggunaAktif();
        DefaultTableModel m = (DefaultTableModel) tblRiwayat.getModel();
        m.setRowCount(0);

        if (user == null) {
            tampilkanRingkasan(0, 0, 0, 0);
            return;
        }

        dataRiwayat = new dao.HasilBelajarDao().getRiwayatPelajar(user.getIdPengguna());

        int total = 0, max = 0, min = Integer.MAX_VALUE;
        for (Object[] r : dataRiwayat) {
            m.addRow(r);
            int skor = ((Number) r[2]).intValue();
            total += skor;
            max = Math.max(max, skor);
            min = Math.min(min, skor);
        }
        tampilkanRingkasan(dataRiwayat.size(), total, max, min);
    }
     
     private void tampilkanRingkasan(int jumlah, int total, int max, int min) {
        if (jumlah == 0) {
            lblTotalpelajar1.setText("-");
            lblTotalmateri1.setText("-");
            lblTotalkelas1.setText("-");
        } else {
            lblTotalpelajar1.setText(String.valueOf(Math.round((double) total / jumlah)));
            lblTotalmateri1.setText(String.valueOf(max));
            lblTotalkelas1.setText(String.valueOf(min));
        }
    }
     

    private void tampilkanDetail() {
    int baris = tblRiwayat.getSelectedRow();
    if (baris < 0) {
        JOptionPane.showMessageDialog(this, "Pilih satu riwayat terlebih dahulu.");
        return;
    }
    Object[] r = dataRiwayat.get(tblRiwayat.convertRowIndexToModel(baris));
    if (aksiDetail != null) aksiDetail.accept(r);
}


