    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
String nama     = txtUsername.getText().trim();
    String username = txtUsername1.getText().trim();
    String email    = txtUsername2.getText().trim();
    String tglLahir = txtUsername3.getText().trim();   // format: yyyy-MM-dd
    String password = new String(txtPass.getPassword());
    String kelas    = (String) cmbKelas.getSelectedItem();
    String jk       = (String) cmbJK.getSelectedItem();

    if (nama.isEmpty() || username.isEmpty() || email.isEmpty()
            || tglLahir.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Semua data wajib diisi");
        return;
    }
    if (!email.matches("^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+$")) {
        JOptionPane.showMessageDialog(this, "Format email tidak valid");
        return;
    }
    java.time.LocalDate tgl;
    try {
        tgl = java.time.LocalDate.parse(tglLahir);
    } catch (java.time.format.DateTimeParseException e) {
        JOptionPane.showMessageDialog(this, "Tanggal lahir harus berformat yyyy-MM-dd, contoh: 2010-05-21");
        return;
    }
    if (password.length() < 6) {
        JOptionPane.showMessageDialog(this, "Password minimal 6 karakter");
        return;
    }
    
    
    String error = new AuthController().prosesRegistrasi(
        nama, username, email, password, jk, tglLahir, kelas);

    if (error != null) {
        JOptionPane.showMessageDialog(this, error, "Pendaftaran Gagal",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    JOptionPane.showMessageDialog(this, "Akun berhasil dibuat, silakan masuk");
    txtUsername.setText("");
    txtUsername1.setText("");
    txtUsername2.setText("");
    txtUsername3.setText("");
    txtPass.setText("");

    MenuUtama utama = (MenuUtama) javax.swing.SwingUtilities.getWindowAncestor(this);
    if (utama != null) utama.tampilkan("card3");
                                       
    }//GEN-LAST:event_btnLoginActionPerformed

