public void setData(
        KelasOnline kelas,
        Consumer<KelasOnline> aksiIkuti) {

    lblNama.setText(kelas.getNamaKelas());

    if (kelas.getPengajar() != null) {
        lblPengajar.setText(
            "Pengajar: " + kelas.getPengajar().getNama()
        );
    } else {
        lblPengajar.setText("Pengajar: -");
    }

    String jadwal = "-";

    if (kelas.getTanggalKelas() != null) {
        jadwal = kelas.getTanggalKelas().format(
            DateTimeFormatter.ofPattern("dd MMMM yyyy",
                new Locale("id", "ID"))
        );
    }

    if (kelas.getWaktuMulai() != null) {
        jadwal += " | " + kelas.getWaktuMulai();
    }

    if (kelas.getWaktuSelesai() != null) {
        jadwal += " - " + kelas.getWaktuSelesai();
    }

    lblJadwal.setText(jadwal);

    NumberFormat rupiah = NumberFormat.getCurrencyInstance(
        new Locale("id", "ID")
    );

    lblHarga.setText(
        rupiah.format(kelas.getHarga())
    );

    btnIkut.addActionListener(e -> {
        if (aksiIkuti != null) {
            aksiIkuti.accept(kelas);
        }
    });


    }
