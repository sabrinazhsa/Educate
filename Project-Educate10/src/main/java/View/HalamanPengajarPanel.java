public void muatData() {
    muatRekap();
    model.Pengguna user = controller.SessionManagerController.getPenggunaAktif();
    String nama = (user != null && user.getNama() != null && !user.getNama().isBlank())
            ? user.getNama().trim() : "Pengajar";
    lblUser.setText("HALO, " + nama.toUpperCase() + "!");

    lblTotalpelajar.setText("...");
    lblTotalmateri.setText("...");
    lblTotalkelas.setText("...");

    // Query di thread terpisah supaya tampilan tidak membeku.
    new javax.swing.SwingWorker<int[], Void>() {
        @Override
        protected int[] doInBackground() {
            dao.StatistikDao s = new dao.StatistikDao();
            return new int[]{s.hitungPelajar(), s.hitungMateri(), s.hitungKelasOnline()};
        }
        @Override
        protected void done() {
            try {
                int[] h = get();
                lblTotalpelajar.setText(tampilkanAngka(h[0]));
                lblTotalmateri.setText(tampilkanAngka(h[1]));
                lblTotalkelas.setText(tampilkanAngka(h[2]));
            } catch (Exception ex) {
                lblTotalpelajar.setText("-");
                lblTotalmateri.setText("-");
                lblTotalkelas.setText("-");
            }
        }
    }.execute();
}

private void muatRekap() {
    new javax.swing.SwingWorker<java.util.List<Object[]>,Void>() {
        protected java.util.List<Object[]> doInBackground() throws Exception { return dao.RekapHasilDao.ambil(10); }
        protected void done() {
            try {
                javax.swing.table.DefaultTableModel m=(javax.swing.table.DefaultTableModel)tblAktivitas.getModel();
                m.setRowCount(0);
                for(Object[] row:get())m.addRow(row);
            } catch(Exception ex){javax.swing.JOptionPane.showMessageDialog(HalamanPengajarPanel.this,"Gagal memuat rekap: "+ex.getMessage());}
        }
    }.execute();
}
private void eksporHasil() {
    javax.swing.JFileChooser fc=new javax.swing.JFileChooser();
    fc.setSelectedFile(new java.io.File("rekap_hasil_belajar.csv"));
    if(fc.showSaveDialog(this)!=javax.swing.JFileChooser.APPROVE_OPTION)return;
    java.io.File file=fc.getSelectedFile();
    if(file.exists() && javax.swing.JOptionPane.showConfirmDialog(this,"Timpa file yang sudah ada?","Konfirmasi",javax.swing.JOptionPane.YES_NO_OPTION)!=javax.swing.JOptionPane.YES_OPTION)return;
    try(java.io.Writer w=new java.io.OutputStreamWriter(new java.io.FileOutputStream(file),java.nio.charset.StandardCharsets.UTF_8)) {
        w.write("\uFEFFPelajar,Paket Latihan,Tanggal,Skor\r\n");
        for(Object[] row:dao.RekapHasilDao.ambil(0)) {
            for(int i=0;i<row.length;i++) {
                if(i>0)w.write(",");
                String v=String.valueOf(row[i]);
                w.write("\""+v.replace("\"","\"\"")+"\"");
            }
            w.write("\r\n");
        }
        javax.swing.JOptionPane.showMessageDialog(this,"Ekspor berhasil: "+file.getAbsolutePath());
    }catch(Exception ex){javax.swing.JOptionPane.showMessageDialog(this,"Ekspor gagal: "+ex.getMessage());}
}

private String tampilkanAngka(int n) {
    return n < 0 ? "-" : String.valueOf(n);   // "-" = database tidak bisa diakses
}

