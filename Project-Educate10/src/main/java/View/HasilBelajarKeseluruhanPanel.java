    private void muatDataHasilBelajar() {
    DefaultTableModel model =
            (DefaultTableModel) tblHasil.getModel();

    model.setRowCount(0);

    List<Object[]> daftar =
            controller.tampilkanHasilBelajar();

    for (Object[] data : daftar) {
        model.addRow(data);
    }

    lblTotal.setText(
            "Total Hasil Belajar Keseluruhan : "
            + daftar.size()
    );
}
    
    public void refreshData() {
    muatDataHasilBelajar();
}
