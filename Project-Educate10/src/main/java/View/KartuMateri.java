public void setData(Materi materi, Consumer<Materi> aksiPelajari) {
    lbljUDUL.setText(materi.getNamaMateri() == null ? "-" : materi.getNamaMateri());
    lblTopik.setText("Topik: " + (materi.getTopik() == null ? "-" : materi.getTopik()));
    lblJenis.setText("Jenis: " + (materi.getTipeMateri() == null ? "-" : materi.getTipeMateri()));

    String deskripsi = materi.getDeskripsiMateri();
    if (deskripsi == null || deskripsi.trim().isEmpty()) {
        deskripsi = "Belum ada deskripsi untuk materi ini.";
    }
    lblDesk.setText("<html><div style='width:260px'>" + escapeHtml(deskripsi) + "</div></html>");

    // Hapus listener dinamis sebelumnya agar tidak terpasang berulang saat refresh.
    if (listenerAksi != null) {
        btnPelajari.removeActionListener(listenerAksi);
    }
    listenerAksi = e -> {
        if (aksiPelajari != null) aksiPelajari.accept(materi);
    };
    btnPelajari.addActionListener(listenerAksi);
}

private String escapeHtml(String teks) {
    return teks.replace("&", "&amp;")
               .replace("<", "&lt;")
               .replace(">", "&gt;");
}

