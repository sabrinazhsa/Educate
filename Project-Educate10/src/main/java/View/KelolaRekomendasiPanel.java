    private void muatDataRekomendasi() {
    DefaultTableModel model =
            (DefaultTableModel) tblRekom.getModel();

    model.setRowCount(0);

    List<Object[]> daftar =
            controller.tampilkanRekomendasi();

    for (Object[] data : daftar) {
        model.addRow(data);
    }

    lblTotal.setText(
            "Total Rekomendasi : " + daftar.size()
    );
}

