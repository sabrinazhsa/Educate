    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
    java.awt.Frame frame = (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this);
    FormRekomendasiDialog dialog = new FormRekomendasiDialog(frame, true);
    dialog.setLocationRelativeTo(this);
    dialog.setVisible(true);          // program berhenti di sini sampai dialog ditutup
    if (dialog.isDisimpan()) {
        try { FormRekomendasiDialog d=dialog; dao.CrudDemoDao.jalankan("INSERT INTO rekomendasi (nilai_minimum,nilai_maksimum,isi_rekomendasi,pengajar_id_pengguna,hasil_belajar_id_hasil) VALUES (?,?,?,?,(SELECT MIN(id_hasil) FROM hasil_belajar))",Integer.parseInt(d.getMin()),Integer.parseInt(d.getMaks()),d.getRekomendasi(),dao.CrudDemoDao.pengajar()); muatDataRekomendasi();
            javax.swing.JOptionPane.showMessageDialog(this,"Data berhasil ditambahkan!");
        } catch(Exception ex){dao.CrudDemoDao.pesan(this,ex);} 
    }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
    int baris = tblRekom.getSelectedRow();
    if (baris < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih rekomendasi yang ingin diubah dulu");
        return;
    }
    
    javax.swing.table.TableModel model = tblRekom.getModel();
    int b = tblRekom.convertRowIndexToModel(baris);

    String nilaiMaks     = String.valueOf(model.getValueAt(b, 1));
    String nilaiMin     = String.valueOf(model.getValueAt(b, 2));
    String rekomendasi     = String.valueOf(model.getValueAt(b, 3));

    java.awt.Frame frame = (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this);
    FormRekomendasiDialog dialog = new FormRekomendasiDialog(frame, true);
    dialog.isiForm(nilaiMaks, nilaiMin, rekomendasi);
    dialog.setLocationRelativeTo(this);
    dialog.setVisible(true);

    if (dialog.isDisimpan()) {
        try { FormRekomendasiDialog d=dialog; int id=Integer.parseInt(String.valueOf(model.getValueAt(b,0)));
            dao.CrudDemoDao.jalankan("UPDATE rekomendasi SET nilai_minimum=?,nilai_maksimum=?,isi_rekomendasi=? WHERE id_rekomendasi=?",Integer.parseInt(d.getMin()),Integer.parseInt(d.getMaks()),d.getRekomendasi(),id);
            muatDataRekomendasi();
            javax.swing.JOptionPane.showMessageDialog(this,"Data berhasil diubah!");
        } catch(Exception ex){dao.CrudDemoDao.pesan(this,ex);} 
    }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {                                         
        int row=tblRekom.getSelectedRow();
        if(row<0){javax.swing.JOptionPane.showMessageDialog(this,"Pilih data terlebih dahulu!");return;}
        if(!dao.CrudDemoDao.konfirmasi(this))return;
        try {int id=Integer.parseInt(String.valueOf(tblRekom.getValueAt(tblRekom.convertRowIndexToModel(row),0)));
             dao.PenghapusanBerantaiDao.hapus("rekomendasi",id); muatDataRekomendasi();
             javax.swing.JOptionPane.showMessageDialog(this,"Data berhasil dihapus!");
        }catch(Exception ex){dao.CrudDemoDao.pesan(this,ex);}
    }



