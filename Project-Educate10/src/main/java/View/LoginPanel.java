    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed

    String username = txtUsername.getText().trim();
    String password = new String(txtPass.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Username dan password wajib diisi");
        return;
    }

    Pengguna user = new AuthController().prosesLogin(username, password);
    if (user == null) {
        JOptionPane.showMessageDialog(this, "Username atau password salah!",
                "Login Gagal", JOptionPane.ERROR_MESSAGE);
        return;
    }

    controller.SessionManagerController.masuk(user);   // simpan siapa yang login, dipakai sapaan di Beranda
    txtPass.setText("");

    // pakai menuUtama dari setMenuUtama(); kalau belum di-set, cari jendela induknya
    MenuUtama utama = (menuUtama != null) ? menuUtama
            : (MenuUtama) javax.swing.SwingUtilities.getWindowAncestor(this);
    if (utama != null) {
        utama.bukaDashboard(user);
    }

    // Navigasi ke dashboard akan kita tambahkan setelah
    // menyesuaikan struktur MenuUtama dan role pengguna.
    // TODO add your handling code here:
    }//GEN-LAST:event_btnLoginActionPerformed

