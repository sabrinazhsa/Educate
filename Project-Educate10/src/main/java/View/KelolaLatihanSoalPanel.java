    private void muatDataSoal() {
    DefaultTableModel model =
            (DefaultTableModel) tblSoal.getModel();

    model.setRowCount(0);

    List<Object[]> daftar =
            controller.tampilkanLatihanSoal();

    for (Object[] data : daftar) {
        model.addRow(data);
    }

    lblTotal.setText(
            "Total Soal : " + daftar.size()
    );
}
